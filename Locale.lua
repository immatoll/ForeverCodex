local _, ns = ...

-- English strings are the keys; other locales override them.
local L = setmetatable({}, { __index = function(_, k) return k end })
ns.L = L

-- Language: "auto" follows the client, "deDE" / "enUS" force one. The choice lives
-- in a CVar, the only storage that exists while the addon files load (saved
-- variables are not there yet), so changing it takes a reload.
local register = RegisterCVar or (C_CVar and C_CVar.RegisterCVar)
if register then pcall(register, "ForeverCompanionLang", "auto") end
local okCvar, chosen = pcall(GetCVar, "ForeverCompanionLang")
local lang = (okCvar and (chosen == "deDE" or chosen == "enUS")) and chosen or GetLocale()
ns.Lang = lang
ns.LangSetting = (okCvar and chosen) or "auto"

function ns.SetLanguage(value)
    pcall(SetCVar, "ForeverCompanionLang", value)
    ns.LangSetting = value
end

-- the language a setting resolves to
function ns.ResolveLanguage(value)
    if value == "deDE" or value == "enUS" then return value end
    return GetLocale()
end

