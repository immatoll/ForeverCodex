# Builds Data/Disenchant.lua: what disenchanting an item gives (materials, chance, amount) by quality, kind and item level.
#
# The game's own files do not have this (the loot of a disenchant is decided by the server; the client tables only say
# which item levels fall into which group). The numbers come from the addon DisenchantBuddy (by BreakBB), which has them as
# Lua code; this script reads its files and writes them as plain data in our format. Run it on the PC when that addon
# is updated:
#
#   python tools/build_disenchant.py [path to the DisenchantBuddy folder]
#
# Only what a Classic client (and its Burning Crusade items) can have is taken: groups whose materials are from Wrath or later are left out. The branches meant
# for other versions (Season of Discovery, Mists) are left out; where a branch has a Classic/Forever variant, that one is used.
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(ADDON), "DisenchantBuddy")
OUT = os.path.join(ADDON, "Data", "Disenchant.lua")
MAX_LEVEL = 164


def read(path):
    return open(path, encoding="utf-8").read().replace("\r\n", "\n")


def materials():
    ids = {}
    for m in re.finditer(r"(?:DisenchantBuddy\.Materials\.)?([A-Z_]+)\s*=\s*(\d+)", read(os.path.join(SRC, "Materials.lua"))):
        ids[m.group(1)] = int(m.group(2))
    return ids


def results_block(body):
    # the first `return { ... }` of a branch (braces matched), as a list of (item, chance, min, max)
    i = body.find("return {")
    if i < 0:
        return None
    j = body.index("{", i)
    depth, k = 0, j
    while True:
        if body[k] == "{":
            depth += 1
        elif body[k] == "}":
            depth -= 1
            if depth == 0:
                break
        k += 1
    block = body[j:k + 1]
    out = []
    for m in re.finditer(r"\{itemId = Materials\.(\w+), probability = ([\d.]+), minQuantity = (\d+), maxQuantity = ([^}]*?)\}", block):
        mx = m.group(4).strip()
        if " or " in mx:  # "DisenchantBuddy.IsMoP and 4 or 2": the plain value
            mx = mx.split(" or ")[-1].strip()
        out.append((m.group(1), float(m.group(2)), int(m.group(3)), int(mx)))
    return out


def parse(path, func):
    text = read(path)
    start = text.index("function DisenchantBuddy.%s(" % func)
    end = text.find("\nend\n", start)
    lines = text[start:end].split("\n")[1:]
    branches, cond, body = [], None, []

    def flush():
        if cond is not None:
            branches.append((cond, "\n".join(body)))

    for line in lines:
        m = re.match(r"^    (if|elseif|else)\b(.*)$", line)
        if m:
            flush()
            cond, body = m.group(2), []
            if m.group(1) == "else":
                cond = None
            continue
        body.append(line)
    flush()
    out = []
    mats = materials()
    for cond, body in branches:
        m = re.search(r"itemLevel\s*(<=|==)\s*(\d+)", cond)
        if not m:
            continue
        op, level = m.group(1), int(m.group(2))
        if level > MAX_LEVEL:
            continue
        res = results_block(body)
        if not res:
            continue
        flat = []
        for name, chance, lo, hi in res:
            assert name in mats, (func, level, name)
            flat.append((mats[name], chance, lo, hi))
        if any(i[0] > 29999 for i in flat):  # materials of Wrath and later: not for this client
            continue
        out.append((op, level, flat))
    return out


def main():
    groups = [
        ("armor", "Uncommon.lua", "GetMaterialsForUncommonArmor"),
        ("weapon", "Uncommon.lua", "GetMaterialsForUncommonWeapons"),
        ("rare", "Rare.lua", "GetMaterialsForRareItem"),
        ("epic", "Epic.lua", "GetMaterialsForEpicItem"),
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("-- Generated by tools/build_disenchant.py from the data of the addon DisenchantBuddy (by BreakBB). Do not edit by hand.\n")
        f.write("-- Per group a list of { how, item level, { material, chance in %, least, most, ... } }: \"<=\" counts up to the\n")
        f.write("-- level, \"==\" only that level. The first entry that fits is the one.\n")
        f.write("local _, ns = ...\nns.DisenchantDB = {\n")
        for key, fname, func in groups:
            rows = parse(os.path.join(SRC, "DisenchantResults", fname), func)
            f.write("    %s = {\n" % key)
            for op, level, flat in rows:
                items = ", ".join("%d, %s, %d, %d" % (i, ("%g" % c), lo, hi) for i, c, lo, hi in flat)
                f.write('        { "%s", %d, { %s } },\n' % (op, level, items))
            f.write("    },\n")
            print(key, len(rows), "ranges")
        f.write("}\n")
    print("wrote", OUT)


main()
