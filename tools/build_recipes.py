# Builds Data/Recipes.lua: every profession recipe of the game client, from the public game tables (DB2) that
# wago.tools offers as CSV. Run on the PC, not in the game; the addon only reads the finished Lua file.
#
#   python tools/build_recipes.py [build]        e.g. 1.60.1.71037 (default: the newest "wowf" build)
#
# Tables used: SkillLine (the professions), SkillLineAbility (which spell belongs to which profession, and the
# skill thresholds), SpellEffect (the item a spell makes), SpellReagents (what it needs). Names are not stored:
# the game gives them in the player's language (GetSpellInfo / item data).
import csv, io, json, os, sys, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, "_cache")
OUT = os.path.join(os.path.dirname(HERE), "Data", "Recipes.lua")
UA = {"User-Agent": "Mozilla/5.0"}

# the profession skill lines that make things: id -> the name the addon uses
LINES = {164: "Blacksmithing", 165: "Leatherworking", 171: "Alchemy", 197: "Tailoring", 202: "Engineering",
         333: "Enchanting", 185: "Cooking", 129: "First Aid", 186: "Mining", 40: "Poisons"}
CREATE_ITEM = 24  # SPELL_EFFECT_CREATE_ITEM


def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60).read()


def newest_build():
    builds = json.loads(get("https://wago.tools/api/builds"))
    return builds["wowf"][0]["version"]


def table(name, build):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, "%s_%s.csv" % (name, build))
    if not os.path.exists(path):
        print("downloading", name)
        data = get("https://wago.tools/db2/%s/csv?build=%s" % (name, build))
        open(path, "wb").write(data)
    return csv.DictReader(io.StringIO(open(path, encoding="utf-8").read()))


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else newest_build()
    print("build", build)

    makes = {}  # spell -> item it creates
    for r in table("SpellEffect", build):
        if r["Effect"] == str(CREATE_ITEM) and int(r["EffectItemType"] or 0) > 0 and r["DifficultyID"] in ("0", ""):
            makes.setdefault(int(r["SpellID"]), int(r["EffectItemType"]))

    needs = {}  # spell -> [(item, count)]
    for r in table("SpellReagents", build):
        spell = int(r["SpellID"])
        lst = []
        for i in range(8):
            item, n = int(r["Reagent_%d" % i] or 0), int(r["ReagentCount_%d" % i] or 0)
            if item > 0 and n > 0:
                lst.append((item, n))
        if lst:
            needs[spell] = lst

    recipes = {name: [] for name in LINES.values()}
    for r in table("SkillLineAbility", build):
        line = int(r["SkillLine"])
        if line not in LINES:
            continue
        spell = int(r["Spell"])
        # a recipe makes something or needs something; the profession's own "learn" spells have neither
        if spell not in makes and spell not in needs:
            continue
        recipes[LINES[line]].append((spell, makes.get(spell, 0), int(r["MinSkillLineRank"] or 0),
                                     int(r["TrivialSkillLineRankLow"] or 0), int(r["TrivialSkillLineRankHigh"] or 0),
                                     needs.get(spell, [])))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    total = 0
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("-- Generated by tools/build_recipes.py from the public game tables of build %s. Do not edit by hand.\n" % build)
        f.write("-- Per profession: { spell, item it makes (0: none, e.g. an enchant), min skill, skill where it turns\n")
        f.write("-- yellow/green (the low trivial value), skill where it turns grey, { reagent item, count, ... } }\n")
        f.write("local _, ns = ...\n")
        f.write('ns.RecipeDB = { build = "%s", professions = {\n' % build)
        for name in sorted(recipes):
            rows = sorted(recipes[name])
            total += len(rows)
            f.write('    ["%s"] = {\n' % name)
            for spell, item, minr, low, high, reag in rows:
                flat = ",".join("%d,%d" % x for x in reag)
                f.write("        { %d, %d, %d, %d, %d, { %s } },\n" % (spell, item, minr, low, high, flat))
            f.write("    },\n")
        f.write("} }\n")
    print("wrote", OUT, total, "recipes")
    for name in sorted(recipes):
        print("  %-15s %d" % (name, len(recipes[name])))


main()
